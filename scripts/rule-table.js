import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const LEVELS = { 0: 'off', 1: 'warn', 2: 'error' };

const level = (entry) => {
  const raw = Array.isArray(entry) ? entry[0] : entry;

  return LEVELS[raw] ?? raw;
};

const format = (entry) => {
  if (entry === undefined) return '-';
  const options = Array.isArray(entry) ? entry.slice(1) : [];

  return [level(entry), ...options.map((o) => JSON.stringify(o))].join(' ');
};

/** Last-wins merge of every `rules` object in a config array (ignores `files` scoping). */
const effective = (config) => Object.assign({}, ...config.map((item) => item.rules ?? {}));

/**
 * Rows for every rule where `config` is on and differs from `baseline`.
 * @returns {Array<{ rule: string, ours: string, recommended: string, source: string }>}
 */
export function buildRuleTable(config, baseline, sources = {}) {
  const ours = effective(config);
  const base = effective(baseline);

  return Object.keys(ours)
    .sort()
    .filter((rule) => level(ours[rule]) !== 'off' || base[rule] !== undefined)
    .filter((rule) => format(ours[rule]) !== format(base[rule]))
    .map((rule) => ({ rule, ours: format(ours[rule]), recommended: format(base[rule]), source: sources[rule] ?? 'new' }));
}

export function renderTable(title, rows) {
  const lines = rows.map((r) => `| \`${r.rule}\` | ${r.ours} | ${r.recommended} | ${r.source} | open |`);

  return [`## ${title}`, '', '| Rule | Ours | Recommended | Source | Decision |', '|---|---|---|---|---|', ...lines, ''].join('\n');
}

async function main() {
  const [{ default: js }, { default: tseslint }, base, baseTs, react, reactTs] = await Promise.all([
    import('@eslint/js'),
    import('typescript-eslint'),
    import('../packages/eslint-config-base/src/index.js'),
    import('../packages/eslint-config-base/src/typescript.js'),
    import('../packages/eslint-config-react/src/index.js'),
    import('../packages/eslint-config-react/src/typescript.js'),
  ]);
  const sources = JSON.parse(fs.readFileSync(path.join(here, 'rule-sources.json'), 'utf8'));
  const recommended = [js.configs.recommended];
  const tsRecommended = [...recommended, ...tseslint.configs.recommendedTypeChecked, ...tseslint.configs.stylisticTypeChecked];
  const tsConfig = baseTs.createTypescriptConfig();
  const reactTsConfig = reactTs.createReactTypescriptConfig();

  const out = [
    '# Rule comparison',
    '',
    'Generated by `npm run rules`. Rows are rules where our setting differs from the baseline; the Decision column is filled during the rule review.',
    '',
    renderTable('Base JS (vs. @eslint/js recommended)', buildRuleTable(base.default, recommended, sources)),
    renderTable('Base TypeScript (vs. @eslint/js + typescript-eslint recommended/stylistic type-checked)', buildRuleTable(tsConfig, tsRecommended, sources)),
    renderTable('React JS (vs. Base JS)', buildRuleTable(react.default, base.default, sources)),
    renderTable('React TypeScript (vs. Base TypeScript)', buildRuleTable(reactTsConfig, tsConfig, sources)),
  ].join('\n');
  fs.writeFileSync(path.join(here, '..', 'docs', 'rules.md'), out);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
